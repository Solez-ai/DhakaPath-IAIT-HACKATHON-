/* ------------------------------------------------------------------ hubs */

export const HUBS = DATA_HUBS.map(entry => ({
  id: entry.id,
  name: entry.name,
  lat: entry.lat,
  lng: entry.lng,
  services: entry.services,
  datasetIds: entry.datasetIds,
  aliases: entry.aliases || [],
  interchange: Boolean(entry.interchange),
  zone: entry.interchange ? 'Interchange' : (entry.services[0] === 'mrt6' ? 'MRT-6 corridor' : 'Bus corridor')
}));

export const HUB_BY_ID = new Map(HUBS.map(entry => [entry.id, entry]));

export function hub(id) {
  return HUB_BY_ID.get(id) || null;
}

/* ------------------------------------------------------------------ links */

function hopTime(line, hop) {
  const operations = OPERATIONS[line.mode];
  const moving = (hop.km / operations.speedKmh) * 60;
  return Math.max(1, Math.round(moving + operations.dwellMin + (line.mode === 'bus' ? 1 : 0)));
}

const generated = [];

LINES.forEach(line => {
  const operations = OPERATIONS[line.mode];

  line.hops.forEach(hop => {
    const base = {
      id: `${line.id}:${hop.from}>${hop.to}`,
      mode: line.mode,
      lineId: line.id,
      routeName: line.name,
      from: hop.from,
      to: hop.to,
      km: hop.km,
      timeMin: hopTime(line, hop),
      frequencyMin: operations.headwayMin,
      geometry: hop.geometry,
      dataset: `Map Data/json/transit-data.json · ${line.id}`,
      active: true
    };

    generated.push(base);
    generated.push({
      ...base,
      id: `${line.id}:${hop.to}>${hop.from}`,
      from: hop.to,
      to: hop.from,
      geometry: [...hop.geometry].reverse()
    });
  });
});

WALKS.forEach(walk => {
  const timeMin = Math.max(1, Math.round((walk.km / OPERATIONS.walk.speedKmh) * 60));
  const base = {
    id: `walk:${walk.from}>${walk.to}`,
    mode: 'walk',
    lineId: 'walk',
    routeName: 'Walk',
    from: walk.from,
    to: walk.to,
    km: walk.km,
    timeMin,
    frequencyMin: 0,
    geometry: null,
    dataset: 'derived from dataset stop coordinates',
    active: true
  };

  generated.push(base);
  generated.push({ ...base, id: `walk:${walk.to}>${walk.from}`, from: walk.to, to: walk.from });
});

export const LINKS = generated;
export const LINK_BY_ID = new Map(LINKS.map(entry => [entry.id, entry]));

export function linksFrom(hubId) {
  return LINKS.filter(entry => entry.from === hubId);
}

export const DATASET_INFO = DATASET;
export const TRANSFER_HUBS = TRANSFERS;
export const LINES_INFO = LINES.map(line => ({
  id: line.id,
  name: line.name,
  mode: line.mode,
  stops: line.stops,
  totalKm: line.totalKm,
  hopCount: line.hops.length
}));

/* Search tokens: every name the dataset uses, plus the recorded aliases of a
   merged hub ("Shahbag" for "Shahbagh"). Longest first so "Mirpur 10" is eaten
   before "Mirpur". No invented spellings. */
const SEARCH_TOKENS = (() => {
  const tokens = [];
  HUBS.forEach(entry => {
    tokens.push({ token: entry.name.toLowerCase(), hubId: entry.id });
    entry.aliases.forEach(alias => tokens.push({ token: alias.toLowerCase(), hubId: entry.id }));
  });
  return tokens.sort((a, b) => b.token.length - a.token.length);
})();

export function searchTokens() {
  return SEARCH_TOKENS;
}

/* Mode-agnostic summary used by the UI cards, the docs and the chat context. */
export function networkSummary() {
  const byMode = {};
  LINKS.forEach(entry => {
    byMode[entry.mode] = (byMode[entry.mode] || 0) + 1;
  });

  return {
    hubs: HUBS.length,
    links: LINKS.length,
    byMode,
    lines: LINES_INFO.map(line => ({ id: line.id, name: line.name, mode: line.mode, stops: line.stops.length, km: line.totalKm })),
    dataset: DATASET_INFO
  };
}

/* ------------------------------------------------------------------
   Admin mutation surface (Part 1 CMS)
   ------------------------------------------------------------------ */

export function setLinkActive(linkId, active) {
  const entry = LINK_BY_ID.get(linkId);
  if (!entry) return null;
  entry.active = Boolean(active);
  return entry;
}

export function setLinkField(linkId, field, value) {
  const entry = LINK_BY_ID.get(linkId);
  if (!entry || !['km', 'routeName', 'frequencyMin'].includes(field)) return null;
  entry[field] = field === 'km' || field === 'frequencyMin' ? Number(value) : value;
  return entry;
}

export function updateHub(hubId, patch) {
  const entry = HUB_BY_ID.get(hubId);
  if (!entry) return null;
  if (patch.zone !== undefined) entry.zone = String(patch.zone);
  return entry;
}

const EDITABLE_RULES = ['perKm', 'minFare', 'maxFare', 'band', 'studentDiscountPct', 'studentMinFare', 'variance'];

export function setFareRule(mode, patch) {
  const rule = FARE_RULES[mode];
  if (!rule) return null;
  Object.entries(patch).forEach(([key, value]) => {
    if (!EDITABLE_RULES.includes(key)) return;
    if (value === null) {
      rule[key] = null;
      return;
    }
    const numeric = Number(value);
    if (!Number.isFinite(numeric) || numeric < 0) return;
    rule[key] = numeric;
  });
  return rule;
}

const SEED = {
  rules: JSON.parse(JSON.stringify(FARE_RULES)),
  links: new Map(LINKS.map(entry => [entry.id, { active: entry.active, routeName: entry.routeName, km: entry.km, frequencyMin: entry.frequencyMin }]))
};

export function resetFareRule(mode) {
  if (!SEED.rules[mode]) return null;
  Object.assign(FARE_RULES[mode], SEED.rules[mode]);
  return FARE_RULES[mode];
}

export function resetLink(linkId) {
  const seed = SEED.links.get(linkId);
  const target = LINK_BY_ID.get(linkId);
  if (!seed || !target) return null;
  Object.assign(target, seed);
  return target;
}

export function resetNetwork() {
  MODES.forEach(mode => resetFareRule(mode));
  LINKS.forEach(entry => resetLink(entry.id));
  return networkSummary();
}

export function networkOverrides() {
  return {
    links: LINKS.map(entry => ({
      id: entry.id,
      active: entry.active !== false,
      routeName: entry.routeName,
      km: entry.km,
      frequencyMin: entry.frequencyMin
    })),
    rules: Object.fromEntries(MODES.map(mode => [mode, { ...FARE_RULES[mode] }]))
  };
}

export function applyNetworkOverrides(overrides) {
  if (!overrides) return 0;
  let applied = 0;

  (overrides.links || []).forEach(entry => {
    const target = LINK_BY_ID.get(entry.id);
    if (!target) return;
    target.active = entry.active !== false;
    if (entry.routeName) target.routeName = entry.routeName;
    if (Number.isFinite(Number(entry.km))) target.km = Number(entry.km);
    if (Number.isFinite(Number(entry.frequencyMin))) target.frequencyMin = Number(entry.frequencyMin);
    applied += 1;
  });

  Object.entries(overrides.rules || {}).forEach(([mode, patch]) => {
    if (setFareRule(mode, patch)) applied += 1;
  });

  return applied;
}
